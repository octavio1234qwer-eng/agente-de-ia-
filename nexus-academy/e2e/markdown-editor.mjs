// E2E del editor de Markdown del panel: barra de formato, vista previa y render en el aula.
import { readFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import pw from "playwright";

const env = Object.fromEntries(readFileSync(new URL("../.env.local", import.meta.url), "utf8").split("\n").filter((l) => l.includes("=")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
const BASE = process.env.E2E_BASE_URL ?? "http://localhost:3000";
const admin = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
let failures = 0;
const check = (c, l) => { console.log(c ? "✔" : "✘", l); if (!c) failures++; };
const ts = Date.now();
const email = `md.admin.${ts}@test.dev`, password = "Markdown123";
const { data: u } = await admin.auth.admin.createUser({ email, password, email_confirm: true });
await admin.from("profiles").update({ role: "admin" }).eq("id", u.user.id);
const { data: course } = await admin.from("courses").select("id, slug").eq("slug", "diseno-ui-ux").single();
const { data: mod } = await admin.from("modules").select("id").eq("course_id", course.id).order("position").limit(1).single();
const { data: lesson } = await admin.from("lessons").insert({ module_id: mod.id, course_id: course.id, title: `Markdown E2E ${ts}`, type: "article", position: 99 }).select("id").single();
await admin.from("lesson_contents").insert({ lesson_id: lesson.id, course_id: course.id, body: "" });

const browser = await pw.chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on("pageerror", (e) => { console.log("pageerror", String(e)); failures++; });
await page.goto(`${BASE}/login`);
await page.fill("#email", email);
await page.fill("#password", password);
await page.click('button[type="submit"]');
await page.waitForURL((x) => x.pathname === "/cuenta/cursos");
await page.goto(`${BASE}/admin/cursos/${course.id}/lecciones/${lesson.id}`);

const body = page.locator("#body");
await body.click();
await page.click('button[aria-label="Subtítulo"]');
await page.keyboard.type("Principios de contraste");
await page.keyboard.press("End");
await page.keyboard.type("\n\nUsa ");
await page.click('button[aria-label="Negritas"]');
await page.keyboard.type("jerarquía clara");
await page.keyboard.press("End");
await page.keyboard.type(" en cada pantalla.\n");
await page.click('button[aria-label="Lista"]');
await page.keyboard.type("Contraste mínimo 4.5:1");
const text = await body.inputValue();
check(text.includes("## Principios de contraste") && text.includes("**jerarquía clara**") && text.includes("- Contraste mínimo"), "la barra de formato inserta Markdown correcto");
const preview = page.getByTestId("markdown-preview");
check(await preview.locator("h2", { hasText: "Principios de contraste" }).count() === 1, "vista previa muestra el subtítulo");
check(await preview.locator("strong", { hasText: "jerarquía clara" }).count() === 1, "vista previa muestra negritas");
check(await preview.locator("li", { hasText: "Contraste mínimo" }).count() === 1, "vista previa muestra la lista");
await page.fill("#body", text + "\n\n<script>alert(1)</script>");
check(await preview.locator("script").count() === 0, "el HTML crudo no se ejecuta en la vista previa (sin XSS)");
await page.click('button:has-text("Guardar lección")');
await page.waitForSelector("text=Lección guardada", { timeout: 15000 });
const { data: saved } = await admin.from("lesson_contents").select("body").eq("lesson_id", lesson.id).single();
check(saved.body.includes("**jerarquía clara**"), "el contenido se guardó");
await page.goto(`${BASE}/aprender/${course.slug}/${lesson.id}`);
check(await page.locator("main h2", { hasText: "Principios de contraste" }).count() === 1 && await page.locator("main strong", { hasText: "jerarquía clara" }).count() === 1, "el alumno ve el mismo formato en el aula");
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(`${BASE}/admin/cursos/${course.id}/lecciones/${lesson.id}`);
await page.click('role=tab[name="Vista previa"]');
check(await page.getByTestId("markdown-preview").isVisible() && !(await page.locator("#body").isVisible()), "en móvil se alterna entre escribir y vista previa");
await page.screenshot({ path: "test-results/markdown-editor-mobile.png" });
await admin.from("lessons").delete().eq("id", lesson.id);
await browser.close();
console.log(failures === 0 ? "\nEDITOR DE MARKDOWN: TODAS LAS PRUEBAS PASARON" : `\n${failures} PRUEBA(S) FALLARON`);
process.exit(failures === 0 ? 0 : 1);
